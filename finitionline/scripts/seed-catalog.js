const del = db.prepare(`DELETE FROM item_catalog WHERE use_count = 0`);
const ins = db.prepare(`
  INSERT OR IGNORE INTO item_catalog (name_norm, display_name, use_count, last_used_at)
  VALUES (?, ?, 0, datetime('now'))
`);
let removed = 0, added = 0;
db.transaction(() => {
  removed = del.run().changes;
  for (const name of PRODUCTS) {
    added += ins.run(db.normName(name), name.replace(/\s+/g, ' ').trim()).changes;
  }
})();
const total = db.prepare(`SELECT COUNT(*) AS n FROM item_catalog`).get().n;
console.log(`הוסרו ${removed} מוצרים בסיסיים ישנים, נוספו ${added} (${PRODUCTS.length - added} כבר הוזמנו בפועל וקיימים). סה"כ בקטלוג: ${total}`);
